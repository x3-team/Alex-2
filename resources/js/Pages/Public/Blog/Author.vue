const totalExperience = computed(() => {
  if (!props.author?.career_history) return null

  const careerData = typeof props.author.career_history === 'string'
      ? JSON.parse(props.author.career_history)
      : props.author.career_history

  if (!Array.isArray(careerData) || !careerData.length) return null

  const currentYear = new Date().getFullYear()
  let minYearFrom = Infinity
  let maxYearTo = -Infinity
  let hasCurrentJob = false

  careerData.forEach(entry => {
    const from = parseInt(entry.year_from)
    const to = entry.year_to ? parseInt(entry.year_to) : null

    // Находим самую раннюю точку старта
    if (from && from >= 1950 && from <= currentYear) {
      if (from < minYearFrom) {
        minYearFrom = from
      }
    }

    // Проверяем верхнюю границу
    if (to && to >= 1950 && to <= currentYear) {
      if (to > maxYearTo) {
        maxYearTo = to
      }
    } else {
      // Если year_to пустой — значит работает по настоящее время
      hasCurrentJob = true
    }
  })

  // Если не нашли ни одного валидного года начала
  if (minYearFrom === Infinity) return null

  // Если есть текущая работа — считаем до currentYear, иначе до максимального year_to
  const endYear = hasCurrentJob ? currentYear : Math.max(maxYearTo, minYearFrom)
  const totalYears = endYear - minYearFrom

  return totalYears > 0 ? totalYears : null
})

